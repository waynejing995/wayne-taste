"""Build isolated trial workspaces for the context-model skills.

Covers wayne-context-init, wayne-compress, and wayne-ship Phase 8 (the ship -> compress
handoff of the task context file). Each workspace has the layout that
eval/wayne-plan/run_agent.sh expects: repo/ (git), wayne-home/, task.md, and, on the
candidate side, skill/ plus _shared/ beside them.

Usage: uv run --no-project python eval/context-model/build.py <case> <control|candidate> <workspace>
"""


def skill_source(kind: str, side: str, dest: Path) -> None:
    name = {"init": "wayne-context-init", "compress": "wayne-compress", "ship": "wayne-ship"}[kind]
    if kind == "ship":
        ref = "HEAD" if side == "control" else None
        for skill, target in (("wayne-ship", dest / "skill"), ("wayne-checkpoint", dest / "wayne-checkpoint")):
            target.mkdir(parents=True)
            if ref:
                tar = subprocess.run(["git", "-C", str(ROOT), "archive", ref, skill], check=True, capture_output=True).stdout
                subprocess.run(["tar", "-x", "--strip-components=1", "-C", str(target)], input=tar, check=True)
            else:
                shutil.copytree(ROOT / skill, target, dirs_exist_ok=True)
    else:
        shutil.copytree(ROOT / name, dest / "skill")
    shutil.copytree(ROOT / "_shared", dest / "_shared", ignore=shutil.ignore_patterns("__pycache__"))


def task_text(kind: str, side: str, topic: str, goal: str | None) -> str:
    state = "/workspace/wayne-home/projects/repo"
    use = "Use the skill at /workspace/skill/SKILL.md to do this.\n\n" if side == "candidate" or kind == "ship" else ""
    if kind == "init":
        return (f"{use}Before anyone starts the task below, set up the context an agent will need for it. "
                f"Write it to {state}/runs/{topic}/context.md.\n\nTask: {goal}\n\n"
                "You are on your own: do not wait for answers; record any question you would ask in the file. "
                "Do not modify live systems or publish anything. Do not implement the task.\n")
    if kind == "compress":
        extra = ""
        if topic == "vat-fix" and goal == "after-ship":
            extra = f"Start from the handoff packet in {state}/checkpoints/.\n\n"
        return (f"{use}{extra}Run a retro on the finished task `{topic}`. Its session logs are in /workspace/sessions/. "
                f"The project's Wayne state is {state} and the repository is /workspace/repo.\n\n"
                "The user is away and has pre-approved every change to a context file or a CLAUDE.md that you propose. "
                "Anything else (code, checks, tools, skills) you only report. Do not commit, push, or publish.\n")
    # ship
    return (f"{use}The VAT fix is committed and pushed (commits abc1234..def5678, PR #41). The review gate passed and "
            "wayne-verify recorded its pass. Do only the final handoff step of the ship workflow for topic `vat-fix`: "
            "retire the run's working state and write the handoff packet for the next stage. "
            "The checkpoint skill is at /workspace/wayne-checkpoint/SKILL.md. Do not commit, push, or publish.\n")


def build(case: str, side: str, ws: Path) -> None:
    kind, fn = CASES[case]
    if ws.exists():
        sys.exit(f"workspace exists: {ws}")
    (ws / "repo").mkdir(parents=True)
    (ws / STATE).mkdir(parents=True)
    result = fn(ws)
    topic, goal = (result if isinstance(result, tuple) else (result, None))
    if case == "compress-after-ship":
        goal = "after-ship"
    git_init(ws / "repo")
    if side == "candidate" or kind == "ship":
        skill_source(kind, side, ws)
    (ws / "task.md").write_text(task_text(kind, side, topic, goal))


if __name__ == "__main__":
    build(sys.argv[1], sys.argv[2], Path(sys.argv[3]).resolve())
